// In-Memory store backed by file persistence
class DataStore {
  doctors: Doctor[] = [];
  hospitals: (HospitalUser & { passwordHash?: string })[] = [];
  patients: (PatientUser & { passwordHash: string })[] = [];
  appointments: Appointment[] = [];
  vitals: HealthVitalRecord[] = [];
  documents: HealthDocument[] = [];
  beds: BedWardInfo[] = [];
  billing: BillingRecord[] = [];
  emergencies: EmergencyRequest[] = [];
  notifications: AppNotification[] = [];
  logs: HospitalActivityLog[] = [];

  constructor() {
    this.load();
  }

  load() {
    try {
      if (fs.existsSync(DB_FILE)) {
        const data = JSON.parse(fs.readFileSync(DB_FILE, 'utf-8'));
        this.doctors = data.doctors || initialDoctors;
        this.hospitals = (data.hospitals || initialHospitals).map(
          (h: HospitalUser & { passwordHash?: string }) => ({
            ...h,
            passwordHash: h.passwordHash || 'hospital123',
          })
        );
        this.patients = data.patients || initialPatients;
        this.appointments = data.appointments || initialAppointments;
        this.vitals = data.vitals || initialVitals;
        this.documents = data.documents || initialDocuments;
        this.beds = data.beds || initialBeds;
        this.billing = data.billing || initialBilling;
        this.emergencies = data.emergencies || initialEmergencyRequests;
        this.notifications = data.notifications || initialNotifications;
        this.logs = data.logs || initialLogs;
        console.log('[CareBridge DB] Loaded data from persistent storage.');
      } else {
        this.resetToDefaults();
        this.save();
      }
    } catch (err) {
      console.error('[CareBridge DB] Error loading DB file, fallback to defaults:', err);
      this.resetToDefaults();
    }
  }

  resetToDefaults() {
    this.doctors = [...initialDoctors];
    this.hospitals = [...initialHospitals];
    this.patients = [...initialPatients];
    this.appointments = [...initialAppointments];
    this.vitals = [...initialVitals];
    this.documents = [...initialDocuments];
    this.beds = [...initialBeds];
    this.billing = [...initialBilling];
    this.emergencies = [...initialEmergencyRequests];
    this.notifications = [...initialNotifications];
    this.logs = [...initialLogs];
  }

  save() {
    try {
      const data = {
        doctors: this.doctors,
        hospitals: this.hospitals,
        patients: this.patients,
        appointments: this.appointments,
        vitals: this.vitals,
        documents: this.documents,
        beds: this.beds,
        billing: this.billing,
        emergencies: this.emergencies,
        notifications: this.notifications,
        logs: this.logs,
      };
      fs.writeFileSync(DB_FILE, JSON.stringify(data, null, 2), 'utf-8');
    } catch (err) {
      console.error('[CareBridge DB] Error saving data store:', err);
    }
  }
}

export const db = new DataStore();
